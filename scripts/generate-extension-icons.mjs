import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, '../public/icons');
const sizes = [16, 32, 48, 128];

mkdirSync(outDir, { recursive: true });

const skullPath = join(outDir, '1337-skull.png');
const skullB64 = readFileSync(skullPath).toString('base64');

function skullIconSvg(size) {
  const pad = Math.round(size * 0.08);
  const inner = size - pad * 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" role="img" aria-label="1337">
  <rect width="${size}" height="${size}" rx="${Math.round(size * 0.19)}" fill="#050806"/>
  <image href="data:image/png;base64,${skullB64}" x="${pad}" y="${pad}" width="${inner}" height="${inner}" preserveAspectRatio="xMidYMid meet"/>
</svg>`;
}

for (const w of sizes) {
  const resvg = new Resvg(skullIconSvg(w), { fitTo: { mode: 'width', value: w } });
  const png = resvg.render();
  const buf = png.asPng();
  const path = join(outDir, `icon-${w}.png`);
  writeFileSync(path, buf);
  console.log('wrote', path);
}

writeFileSync(join(outDir, '1337-logo.svg'), skullIconSvg(128));
console.log('wrote', join(outDir, '1337-logo.svg'));

const websitePublic = join(__dirname, '../website/public');
const skullSvg = readFileSync(join(outDir, '1337-skull.svg'));
writeFileSync(join(websitePublic, '1337-skull.svg'), skullSvg);
writeFileSync(join(websitePublic, 'logo.svg'), skullSvg);
writeFileSync(join(websitePublic, 'icon-128.png'), readFileSync(join(outDir, 'icon-128.png')));
console.log('wrote', join(websitePublic, '1337-skull.svg'));
console.log('wrote', join(websitePublic, 'logo.svg'));
console.log('wrote', join(websitePublic, 'icon-128.png'));

const icon128 = readFileSync(join(outDir, 'icon-128.png'));
writeFileSync(
  join(__dirname, '../src/lib/providerIcon1337.generated.ts'),
  `/** Generated by scripts/generate-extension-icons.mjs — do not edit */\nexport const ICON_1337_DATA_URI = 'data:image/png;base64,${icon128.toString('base64')}' as const;\n`,
);
console.log('wrote', join(__dirname, '../src/lib/providerIcon1337.generated.ts'));
