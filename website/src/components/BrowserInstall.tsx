function BrowserIcon({ id, className }: { id: SupportedBrowserId; className?: string }) {
  switch (id) {
    case 'chrome':
      return <ChromeMark className={className} />;
    case 'brave':
      return <BraveMark className={className} />;
    case 'opera':
      return <OperaMark className={className} />;
    case 'arc':
      return <ArcMark className={className} />;
  }
}

function storeProps(name: string) {
  return {
    href: SITE.chromeStoreUrl,
    target: '_blank' as const,
    rel: 'noopener noreferrer',
    'aria-label': `Install 1337 on ${name} (Chrome Web Store)`,
  };
}

